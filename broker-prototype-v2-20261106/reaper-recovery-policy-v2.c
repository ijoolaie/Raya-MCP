#include "reaper-recovery-policy-v2.h"
#define POLLING_CAUSES (RAYA_RECOVERY_CAUSE_WAKE_SIGNAL | RAYA_RECOVERY_CAUSE_WAIT_FAILED)
#define BLOCKING_CAUSES (RAYA_RECOVERY_CAUSE_COMPLETION_UNCERTAIN | RAYA_RECOVERY_CAUSE_OWNERSHIP_INVARIANT | RAYA_RECOVERY_CAUSE_HANDLE_CLOSE | RAYA_RECOVERY_CAUSE_WAITSET_INVALID)
#define ALL_CAUSES (POLLING_CAUSES | BLOCKING_CAUSES)
raya_recovery_decision raya_recovery_policy_evaluate(uint32_t causes) {
 if (causes==RAYA_RECOVERY_CAUSE_NONE || (causes & ~ALL_CAUSES)!=0) return RAYA_RECOVERY_BLOCKED;
 if ((causes & BLOCKING_CAUSES)!=0) return RAYA_RECOVERY_BLOCKED;
 return RAYA_RECOVERY_POLLING_ELIGIBLE;
}
